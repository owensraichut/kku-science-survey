/**
 * แปลผลค่าเฉลี่ยตามเกณฑ์ของเบสท์ (Best) 5 ระดับ
 * @param {number} avg ค่าเฉลี่ย
 * @returns {{text: string, level: number}}
 */
function interpretScore(avg) {
    if (!avg && avg !== 0) return { text: "-", level: 0 };
    if (avg >= 4.51) return { text: "มากที่สุด", level: 5 };
    if (avg >= 3.51) return { text: "มาก", level: 4 };
    if (avg >= 2.51) return { text: "ปานกลาง", level: 3 };
    if (avg >= 1.51) return { text: "น้อย", level: 2 };
    return { text: "น้อยที่สุด", level: 1 };
}

/**
 * คำนวณค่าเฉลี่ยของชุดตัวเลข
 * @param {number[]} values
 * @returns {number|null}
 */
function calcMean(values) {
    const nums = values.filter(v => typeof v === "number" && !isNaN(v));
    if (nums.length === 0) return null;
    return nums.reduce((sum, v) => sum + v, 0) / nums.length;
}

/**
 * คำนวณส่วนเบี่ยงเบนมาตรฐานของกลุ่มตัวอย่าง (Sample S.D.)
 * @param {number[]} values
 * @returns {number|null}
 */
function calcSD(values) {
    const nums = values.filter(v => typeof v === "number" && !isNaN(v));
    if (nums.length < 2) return null;
    const mean = nums.reduce((sum, v) => sum + v, 0) / nums.length;
    const variance = nums.reduce((sum, v) => sum + Math.pow(v - mean, 2), 0) / (nums.length - 1);
    return Math.sqrt(variance);
}

